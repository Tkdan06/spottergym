export function guideBySlug(slug: string | undefined) {
  if (!slug) return undefined
  const clean = slug.replace(/\/index\.html$/i, '').replace(/\/+$/, '')
  if (!clean) return undefined
  return GUIDE_ARTICLES.find((a) => a.slug === clean)
}
