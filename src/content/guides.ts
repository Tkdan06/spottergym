export function guideIndexCards() {
  const dating = GUIDE_ARTICLES.find((a) => a.slug === 'znakomstva-v-zale')
  const safety = GUIDE_ARTICLES.find((a) => a.slug === 'bezopasnost')
  const cards: { path: string; kicker: string; title: string; preview: string }[] = []
  if (dating) {
    cards.push({
      path: dating.path,
      kicker: dating.kicker,
      title: dating.title,
      preview: guideLeadPreview(dating),
    })
  }
  cards.push({
    path: WORKOUTS_HUB.path,
    kicker: WORKOUTS_HUB.kicker,
    title: WORKOUTS_HUB.h1,
    preview: WORKOUTS_HUB.indexPreview,
  })
  if (safety) {
    cards.push({
      path: safety.path,
      kicker: safety.kicker,
      title: safety.title,
      preview: guideLeadPreview(safety),
    })
  }
  return cards
}

export function guideBySlug(slug: string | undefined) {
  if (!slug) return undefined
  const clean = slug.replace(/\/index\.html$/i, '').replace(/\/+$/, '')
  if (!clean) return undefined
  return GUIDE_ARTICLES.find((a) => a.slug === clean)
}
