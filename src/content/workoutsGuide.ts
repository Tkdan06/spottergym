const bySlug = new Map(WORKOUTS_ARTICLES.map((article) => [article.slug, article]))

export function workoutsArticleBySlug(slug: string | undefined) {
  if (!slug) return undefined
  const clean = slug.replace(/\/index\.html$/i, '').replace(/\/+$/, '')
  return bySlug.get(clean as WorkoutsArticleSlug)
}

export function workoutsRelated(article: WorkoutsArticle) {
  return article.related
    .map((slug) => bySlug.get(slug))
    .filter((item): item is WorkoutsArticle => Boolean(item))
}
